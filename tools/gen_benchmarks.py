"""Generate docs/BENCHMARKS.md from a bench.json run (every figure from the run)."""
import json
import sys
from pathlib import Path

src = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(
    r"C:/Users/ETCMC/AppData/Local/hermes/cache/scratch/mg-bench2/bench.json")
d = json.loads(src.read_text(encoding="utf-8"))
out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path("docs/BENCHMARKS.md")


def us(v):
    return f"{v:,.0f}"


L = []
L.append("# Benchmarks — measured, reproducible")
L.append("")
L.append("Generated by tools/bench.py from this run's bench.json. Reproduce with:")
L.append("PYTHONPATH=src python tools/bench.py . <outdir>  (Python 3.12, stdlib + cryptography only).")
L.append("")
L.append(f"Environment: Python {d['python']}, {d['platform']}, cryptography {d.get('cryptography', 'n/a')}.")
L.append("Timings are median of N runs after 2 warmup runs; single process, local disk, fsync on append.")
L.append("")
L.append("## Hot-path throughput (ops/sec)")
L.append("| operation | ops/sec | median µs |")
L.append("|---|---|---|")
for k, label in [("evaluate_pure", "guard.evaluate (pure, no ledger)"),
                 ("verify_decision_offline", "verify.decision (offline, Ed25519)"),
                 ("decide_allow_commit_n200", "guard.decide ALLOW + commit")]:
    r = d[k]
    L.append(f"| {label} | {r['ops_per_sec']:,.0f} | {us(r['median_us'])} |")
L.append("")
L.append("## Ledger append latency vs size (full-history rewrite + fsync)")
L.append("| entries | median µs/append |")
L.append("|---|---|")
for k, v in d["append_latency_by_ledger_size"].items():
    L.append(f"| {k} | {us(v['median_us'])} |")
L.append("")
L.append("## Hash-chain verify vs size")
L.append("| entries | median µs |")
L.append("|---|---|")
for k, v in d["verify_chain_by_ledger_size"].items():
    L.append(f"| {k} | {us(v['median_us'])} |")
L.append("")
L.append("## Tamper detection latency (one mutated mid-chain entry; all detected)")
L.append("| entries | median µs | detected |")
L.append("|---|---|---|")
for k, v in d["tamper_detection_by_ledger_size"].items():
    L.append(f"| {k} | {us(v['median_us'])} | {v['detected']} |")
L.append("")
L.append("## Red-team adversary throughput (real engine, offline, deterministic)")
L.append("| adversary | attacks | seconds | attacks/sec |")
L.append("|---|---|---|---|")
for r in d["redteam_throughput"]:
    L.append(f"| {r['adversary']} | {r['attacks']} | {r['seconds']} | {r['attacks_per_sec']:,.0f} |")
L.append("")
L.append("## Honest caveats")
_app500 = d["append_latency_by_ledger_size"].get("500", {}).get("median_us", 0) / 1000.0
L.append("- Append and verify are O(n): the ledger rewrites full history and fsyncs on every append. "
         f"At 500 entries an append is ~{_app500:.0f} ms; this is a deliberate durability trade-off, not a hidden cost. "
         "For high write rates, batch or shard ledgers.")
L.append("- Single-writer is enforced by an exclusive lock; concurrent writers fail closed rather than corrupt.")
L.append("- Numbers are single-machine, single-process; they are a floor for comparison, not a distributed-systems claim.")
L.append("- The fuzzer reports partial coverage when draws are schema-invalid; throughput counts issued attacks, "
         "not only those that reached a decision.")
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(L) + "\n", encoding="utf-8")
print("wrote", out, len(L), "lines")
